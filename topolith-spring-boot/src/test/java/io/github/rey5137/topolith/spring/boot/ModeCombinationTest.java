package io.github.rey5137.topolith.spring.boot;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import io.github.rey5137.topolith.spring.boot.fixture.billing.BillingAutoConfiguration;
import io.github.rey5137.topolith.spring.boot.fixture.billing.BillingComponent;
import io.github.rey5137.topolith.spring.boot.fixture.billing.BillingEntry;
import io.github.rey5137.topolith.spring.boot.fixture.billing.BillingRepository;
import io.github.rey5137.topolith.spring.boot.fixture.host.Hosts.Host;
import io.github.rey5137.topolith.spring.boot.fixture.ledger.LedgerAutoConfiguration;
import io.github.rey5137.topolith.spring.boot.fixture.ledger.LedgerComponent;
import io.github.rey5137.topolith.spring.boot.fixture.ledger.LedgerEntry;
import io.github.rey5137.topolith.spring.boot.fixture.ledger.LedgerRepository;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.springframework.boot.test.context.assertj.AssertableApplicationContext;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.orm.jpa.persistenceunit.PersistenceManagedTypes;

import static org.junit.jupiter.api.Assertions.*;

class ModeCombinationTest {
    @TempDir
    Path root;

    @ParameterizedTest
    @CsvSource({"false, internal, internal", "false, internal, none", "false, none, internal", "false, none, none",
            "true, internal, internal", "true, internal, none", "true, none, internal", "true, none, none"})
    void ac_road_01_modes_leave_no_activation_for_disabled_modules(boolean singleJar, String ledger, String billing)
            throws Exception {
        Path first = Fixtures.dir(root, "first");
        Path second = singleJar ? first : Fixtures.dir(root, "second");
        module(first, "ledger", Fixtures.LEDGER, LedgerEntry.class, LedgerRepository.class, LedgerComponent.class,
                LedgerAutoConfiguration.class);
        module(second, "billing", Fixtures.BILLING, BillingEntry.class, BillingRepository.class,
                BillingComponent.class, BillingAutoConfiguration.class);
        if (singleJar) {
            Fixtures.imports(first, LedgerAutoConfiguration.class.getName(), BillingAutoConfiguration.class.getName());
        } else {
            Fixtures.imports(first, LedgerAutoConfiguration.class.getName());
            Fixtures.imports(second, BillingAutoConfiguration.class.getName());
        }
        Path[] roots = singleJar ? new Path[] {first} : new Path[] {first, second};
        try (Fixtures.RecordingLoader loader = new Fixtures.RecordingLoader(roots)) {
            new ApplicationContextRunner().withClassLoader(loader).withUserConfiguration(Host.class)
                    .withPropertyValues("spring.liquibase.enabled=false", "spring.jpa.hibernate.ddl-auto=none",
                            "management.endpoints.web.exposure.include=topolith",
                            "topolith.modules.ledger.mode=" + ledger, "topolith.modules.billing.mode=" + billing)
                    .run(context -> {
                        assertNull(context.getStartupFailure());
                        check(context, "ledger", ledger, LedgerComponent.class, LedgerAutoConfiguration.class,
                                LedgerEntry.class, LedgerRepository.class);
                        check(context, "billing", billing, BillingComponent.class, BillingAutoConfiguration.class,
                                BillingEntry.class, BillingRepository.class);
                        Map<?, ?> reported = (Map<?, ?>) context.getBean(TopolithEndpoint.class).modules().get("modules");
                        assertEquals(Map.of("mode", ledger), reported.get("ledger"));
                        assertEquals(Map.of("mode", billing), reported.get("billing"));
                    });
        }
    }

    private void module(Path path, String id, String pkg, Class<?>... classes) throws Exception {
        Fixtures.module(path, id, pkg, List.of(pkg + ".api"));
        Fixtures.resource(path, "db/modules/" + id + "/V1__init.sql", "create table " + id
                + "_entry (id bigint generated by default as identity primary key, memo varchar(255));");
        for (Class<?> type : classes) {
            String name = type.getName().replace('.', '/') + ".class";
            Path target = path.resolve(name);
            Files.createDirectories(target.getParent());
            try (var input = type.getClassLoader().getResourceAsStream(name)) {
                Files.copy(input, target);
            }
        }
    }

    private void check(AssertableApplicationContext context, String id, String mode, Class<?> component,
            Class<?> configuration, Class<?> entity, Class<?> repository) {
        boolean active = mode.equals("internal");
        assertEquals(active ? 1 : 0, context.getBeansOfType(component).size(), id + " component");
        assertEquals(active ? 1 : 0, context.getBeansOfType(configuration).size(), id + " auto-configuration");
        assertEquals(active, context.containsBean(id + "Marker"), id + " auto-configuration bean");
        assertEquals(active, context.getBean(PersistenceManagedTypes.class).getManagedClassNames()
                .contains(entity.getName()), id + " entity");
        assertEquals(active ? 1 : 0, context.getBeansOfType(repository).size(), id + " repository");
        assertEquals(active, context.containsBean("topolith.flyway." + id), id + " migration bean");
        Integer tables = new JdbcTemplate(context.getBean(javax.sql.DataSource.class)).queryForObject(
                "select count(*) from information_schema.tables where lower(table_name) in (?, ?)", Integer.class,
                id + "_entry", "flyway_schema_history_" + id);
        assertEquals(active ? 2 : 0, tables, id + " migration tables");
    }
}
